"""Core Pydantic v2 models for AutoLab state.

Every model has strict validation, frozen value semantics where appropriate,
and JSON round-trippable. These are the lingua franca passed between agents,
the verifier, and the persistence layer.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Annotated, Any, Literal
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


def _utc_now() -> datetime:
    """Return a timezone-aware UTC timestamp."""
    return datetime.now(UTC)


Confidence = Annotated[float, Field(ge=0.0, le=1.0)]


class _Frozen(BaseModel):
    """Base for immutable, hashable value models."""

    model_config = ConfigDict(frozen=True, extra="forbid", str_strip_whitespace=True)


class _Mutable(BaseModel):
    """Base for mutable container models."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


CitationSource = Literal["arxiv", "pubmed", "manual"]


class Citation(_Frozen):
    """A literature reference grounding a claim."""

    source: CitationSource
    identifier: str
    title: str
    url: str | None = None
    year: int | None = None


class Hypothesis(_Frozen):
    """A scientific hypothesis produced by the Research Agent."""

    id: UUID = Field(default_factory=uuid4)
    question: str
    statement: str
    rationale: str
    citations: tuple[Citation, ...] = ()
    confidence: Confidence = 0.5
    created_at: datetime = Field(default_factory=_utc_now)


ParameterValue = float | int | str | bool


class ExperimentParameter(_Frozen):
    """A single named parameter for an experiment protocol."""

    name: str
    value: ParameterValue
    unit: str | None = None


class ExperimentDesign(_Frozen):
    """A concrete protocol with parameters, generated by the Design Agent."""

    id: UUID = Field(default_factory=uuid4)
    hypothesis_id: UUID
    protocol: str
    parameters: tuple[ExperimentParameter, ...] = ()
    estimated_cost_usd: float = Field(ge=0.0)
    estimated_duration_minutes: float = Field(ge=0.0)
    success_criteria: tuple[str, ...] = ()


class Measurement(_Frozen):
    """A single numeric measurement from an experiment."""

    name: str
    value: float
    unit: str | None = None
    timestamp: datetime = Field(default_factory=_utc_now)


ExperimentStatus = Literal["success", "partial", "failure"]


class ExperimentResult(_Frozen):
    """Raw outcome of running an `ExperimentDesign`."""

    id: UUID = Field(default_factory=uuid4)
    design_id: UUID
    status: ExperimentStatus
    measurements: tuple[Measurement, ...] = ()
    raw_artifacts: tuple[str, ...] = ()
    notes: str = ""
    completed_at: datetime = Field(default_factory=_utc_now)


ClaimType = Literal["premise", "inference", "conclusion"]


class ReasoningStep(_Frozen):
    """A single step inside a chain-of-thought."""

    index: int = Field(ge=0)
    claim: str
    claim_type: ClaimType
    referenced_step_indices: tuple[int, ...] = ()

    @model_validator(mode="after")
    def _refs_are_backward(self) -> ReasoningStep:
        for ref in self.referenced_step_indices:
            if ref >= self.index:
                raise ValueError(
                    f"referenced_step_indices must be < index; got {ref} for index {self.index}"
                )
            if ref < 0:
                raise ValueError(f"referenced_step_indices must be non-negative; got {ref}")
        return self


class ReasoningTrace(_Frozen):
    """An ordered chain of reasoning steps produced by an agent."""

    id: UUID = Field(default_factory=uuid4)
    agent: str
    steps: tuple[ReasoningStep, ...]
    produced_at: datetime = Field(default_factory=_utc_now)

    @field_validator("steps")
    @classmethod
    def _indices_are_dense(cls, steps: tuple[ReasoningStep, ...]) -> tuple[ReasoningStep, ...]:
        for expected, step in enumerate(steps):
            if step.index != expected:
                raise ValueError(
                    f"steps must have dense 0-based indices; expected {expected}, got {step.index}"
                )
        return steps


Verdict = Literal["VALID", "INVALID", "UNGROUNDED"]


class StepVerdict(_Frozen):
    """The verifier's verdict on a single reasoning step."""

    step_index: int = Field(ge=0)
    verdict: Verdict
    details: str = ""


class VerificationResult(_Frozen):
    """Aggregate verdict over a `ReasoningTrace`."""

    trace_id: UUID
    step_verdicts: tuple[StepVerdict, ...]
    consistency_score: Confidence
    summary: str = ""

    @model_validator(mode="after")
    def _verdicts_have_unique_indices(self) -> VerificationResult:
        seen: set[int] = set()
        for v in self.step_verdicts:
            if v.step_index in seen:
                raise ValueError(f"duplicate step_index {v.step_index} in step_verdicts")
            seen.add(v.step_index)
        return self


class ConfidenceScore(_Frozen):
    """A confidence value with a one-line basis."""

    value: Confidence
    basis: str


class HITLRequest(_Mutable):
    """A request escalated to a human for resolution."""

    id: UUID = Field(default_factory=uuid4)
    agent: str
    reason: str
    payload: dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=_utc_now)


